def find_paragraph(doc: Document, text: str, contains: bool = False) -> Paragraph:
    for paragraph in doc.paragraphs:
        if contains and text in paragraph.text:
            return paragraph
        if not contains and paragraph.text.strip() == text:
            return paragraph
    raise ValueError(f"Paragraph not found: {text}")


def clear_paragraph(paragraph: Paragraph) -> None:
    paragraph.text = ""


def set_paragraph_text(paragraph: Paragraph, text: str) -> None:
    clear_paragraph(paragraph)
    paragraph.add_run(text)


def remove_paragraph(paragraph: Paragraph) -> None:
    element = paragraph._element
    parent = element.getparent()
    if parent is not None:
        parent.remove(element)


def insert_paragraph_before(reference: Paragraph, text: str, style_name: str | None = None) -> Paragraph:
    if style_name is not None:
        doc = reference.part.document
        sample = next((paragraph for paragraph in doc.paragraphs if paragraph.style.name == style_name), None)
        if sample is not None:
            new_p = deepcopy(sample._p)
            for child in list(new_p):
                if not child.tag.endswith("}pPr"):
                    new_p.remove(child)
            reference._p.addprevious(new_p)
            new_paragraph = Paragraph(new_p, reference._parent)
            if text:
                new_paragraph.add_run(text)
            return new_paragraph
    doc = reference.part.document
    new_paragraph = doc.add_paragraph(text)
    reference._p.addprevious(new_paragraph._p)
    return new_paragraph


def insert_table_before(reference: Paragraph, rows: list[list[str]], style_name: str = "Table Grid") -> None:
    parent = reference._parent
    doc = parent.part.document
    table = doc.add_table(rows=len(rows), cols=len(rows[0]))
    table.style = style_name
    for r_idx, row in enumerate(rows):
        for c_idx, value in enumerate(row):
            table.cell(r_idx, c_idx).text = value
    reference._p.addprevious(table._tbl)


def set_table_row(table, row_index: int, title: str, description: str, deadline: str | None = None) -> None:
    table.rows[row_index].cells[1].text = title
    table.rows[row_index].cells[2].text = description
    if deadline is not None:
        table.rows[row_index].cells[3].text = deadline


